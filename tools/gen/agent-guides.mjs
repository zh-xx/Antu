// ============================================================
//  tools/gen/agent-guides.mjs — embed each type's mechanism notes as a JS module
//
//  Source of truth: spec/agent/<type>/guide.md (English only, for agents). The npm
//  entry `@zh-xx/antu/validate` exposes `guide(type)` for a host that builds a prompt
//  without copying the markdown (issue 166). The texts must live in the bundle so the
//  entry works without reading the filesystem (and in a browser).
//
//    node tools/gen/agent-guides.mjs          write src/core/agentGuides.generated.js
//    node tools/gen/agent-guides.mjs --check  exit 1 if that file is stale
// ============================================================

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const REPO = join(fileURLToPath(new URL('../..', import.meta.url)))
const AGENT = join(REPO, 'spec/agent')
export const MODULE = 'src/core/agentGuides.generated.js'

/** { type: markdown text } from every guide.md under spec/agent/ */
export function expectedGuides() {
  if (!existsSync(AGENT)) return {}
  const out = {}
  for (const name of readdirSync(AGENT, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()) {
    const file = join(AGENT, name, 'guide.md')
    if (existsSync(file)) out[name] = readFileSync(file, 'utf8')
  }
  return out
}

export function expectedModuleText() {
  const guides = expectedGuides()
  return (
    '// Generated by tools/gen/agent-guides.mjs from spec/agent/*/guide.md: do not edit by hand.\n' +
    `export const AGENT_GUIDES = ${JSON.stringify(guides, null, 2)}\n`
  )
}

const text = expectedModuleText()
const path = join(REPO, MODULE)
if (process.argv.includes('--check')) {
  if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
    process.stderr.write(`out of date (run node tools/gen/agent-guides.mjs): ${MODULE}\n`)
    process.exitCode = 1
  }
} else {
  writeFileSync(path, text)
  process.stdout.write(`${Object.keys(expectedGuides()).length} guides written to ${MODULE}\n`)
}
