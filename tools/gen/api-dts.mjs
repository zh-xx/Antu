// ============================================================
//  tools/gen/api-dts.mjs — public `.d.ts` for `@zh-xx/antu/validate` and `@zh-xx/antu/html`
//
//  Source of truth: JSDoc on `tools/api/validate.mjs` and `tools/api/html.mjs` (issue 227).
//  Emits declaration files by stubbing their imports (so tsc does not walk the engine) and running
//  `tsc --declaration --emitDeclarationOnly`. Spec JSON types stay in tools/gen/spec-types.mjs;
//  embed's richer host contract stays hand-written until its JSDoc is as complete.
//
//    node tools/gen/api-dts.mjs          write tools/api/validate.d.ts and tools/api/html.d.ts
//    node tools/gen/api-dts.mjs --check  exit 1 if either file is stale
// ============================================================

import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const REPO = join(fileURLToPath(new URL('../..', import.meta.url)))
const TSC = join(REPO, 'node_modules/.bin/tsc')

/** @type {Array<{ src: string, out: string, title: string }>} */
export const MODULES = [
  {
    src: 'tools/api/validate.mjs',
    out: 'tools/api/validate.d.ts',
    title: 'Declarations of `@zh-xx/antu/validate` (from tools/api/validate.mjs JSDoc).',
  },
  {
    src: 'tools/api/html.mjs',
    out: 'tools/api/html.d.ts',
    title: 'Declarations of `@zh-xx/antu/html` (from tools/api/html.mjs JSDoc).',
  },
]

const stubImports = (text) =>
  text
    .split(/\r?\n/)
    .map((line) => (/^import\s/.test(line) ? `// stubbed: ${line}` : line))
    .join('\n')

/** Drop the raw `@typedef` comment blocks; `export type` that follows already carries the shape. */
const stripTypedefComments = (text) =>
  text.replace(/\/\*\*[\s\S]*?@typedef[\s\S]*?\*\/\s*/g, '')

const header = (title) =>
  [
    `// Generated by tools/gen/api-dts.mjs — do not edit by hand.`,
    `// ${title}`,
    `// Contract: spec/embed.md; test/embed.test.mjs checks export names; --check keeps this file in step.`,
    ``,
  ].join('\n')

/**
 * @returns {Record<string, string>} map of repo-relative out path → file text
 */
export function expectedFiles() {
  if (!existsSync(TSC)) {
    throw new Error(`typescript missing at ${TSC} (run npm install)`)
  }
  const dir = mkdtempSync(join(tmpdir(), 'antu-api-dts-'))
  try {
    for (const m of MODULES) {
      const base = m.src.split('/').pop()
      writeFileSync(join(dir, base), stubImports(readFileSync(join(REPO, m.src), 'utf8')))
    }
    writeFileSync(
      join(dir, 'tsconfig.json'),
      `${JSON.stringify(
        {
          compilerOptions: {
            allowJs: true,
            checkJs: false,
            declaration: true,
            emitDeclarationOnly: true,
            strict: true,
            noImplicitAny: false,
            module: 'ESNext',
            moduleResolution: 'bundler',
            target: 'ES2022',
            lib: ['ES2022'],
            skipLibCheck: true,
            outDir: './out',
          },
          include: MODULES.map((m) => `./${m.src.split('/').pop()}`),
        },
        null,
        2,
      )}\n`,
    )
    const r = spawnSync(TSC, ['-p', join(dir, 'tsconfig.json'), '--pretty', 'false'], {
      encoding: 'utf8',
      cwd: dir,
    })
    // Declaration emit can report errors from incomplete stubs; keep going if .d.mts files exist.
    const out = {}
    for (const m of MODULES) {
      const base = m.src.split('/').pop().replace(/\.mjs$/, '')
      const emitted = join(dir, 'out', `${base}.d.mts`)
      const alt = join(dir, 'out', `${base}.d.ts`)
      const path = existsSync(emitted) ? emitted : alt
      if (!existsSync(path)) {
        const detail = (r.stdout || '') + (r.stderr || '')
        throw new Error(`api-dts: no emit for ${m.src}\n${detail}`)
      }
      const body = stripTypedefComments(readFileSync(path, 'utf8')).trimStart()
      out[m.out] = `${header(m.title)}${body.endsWith('\n') ? body : `${body}\n`}`
    }
    return out
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const files = expectedFiles()
  if (process.argv.includes('--check')) {
    let bad = false
    for (const [rel, text] of Object.entries(files)) {
      const path = join(REPO, rel)
      if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
        process.stderr.write(`out of date (run node tools/gen/api-dts.mjs): ${rel}\n`)
        bad = true
      }
    }
    if (bad) process.exitCode = 1
  } else {
    for (const [rel, text] of Object.entries(files)) {
      const path = join(REPO, rel)
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, text)
      process.stdout.write(`wrote ${rel}\n`)
    }
  }
}
