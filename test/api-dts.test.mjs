// tools/api/validate.d.ts, html.d.ts and src/embed/antu-embed.d.ts are written from implementation
// JSDoc (tools/gen/api-dts.mjs) so the published host types stay in step (issue 227).

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { EMBED, MODULES } from '../tools/gen/api-dts.mjs'

test('the generated public .d.ts files match their JSDoc (run `node tools/gen/api-dts.mjs`)', () => {
  const r = spawnSync(process.execPath, ['tools/gen/api-dts.mjs', '--check'], { encoding: 'utf8' })
  assert.equal(r.status, 0, r.stderr || r.stdout)
})

test('generated validate.d.ts names the public result types and exports', () => {
  const text = readFileSync('tools/api/validate.d.ts', 'utf8')
  assert.match(text, /^\/\/ Generated by tools\/gen\/api-dts\.mjs/m)
  for (const name of ['ValidateResult', 'LayoutResult', 'NormalizeResult', 'VersionsReport']) {
    assert.match(text, new RegExp(`export type ${name}\\b`), name)
  }
  for (const fn of ['validate', 'layout', 'normalize', 'describe', 'guide', 'kinds', 'versions']) {
    assert.match(text, new RegExp(`export function ${fn}\\b`), fn)
  }
  assert.match(text, /lang\?: "zh" \| "en"/)
})

test('generated antu-embed.d.ts names the host contract and keeps the theme union', () => {
  const text = readFileSync('src/embed/antu-embed.d.ts', 'utf8')
  assert.match(text, /^\/\/ Generated by tools\/gen\/api-dts\.mjs/m)
  for (const name of [
    'AntuSpec',
    'AntuTheme',
    'AntuLang',
    'AntuThemeTokens',
    'AntuViewState',
    'AntuPersistName',
    'AntuSource',
    'AntuEvent',
    'AntuPrefsStore',
    'MountOptions',
    'AntuHandle',
  ]) {
    assert.match(text, new RegExp(`export type ${name}\\b`), name)
  }
  for (const fn of ['mount', 'validate', 'normalize', 'kindsOf', 'kindIcon', 'kindLabel']) {
    assert.match(text, new RegExp(`export function ${fn}\\b`), fn)
  }
  assert.match(text, /export declare const cardUi\b/)
  assert.match(text, /"document" \| "modern" \| "legal" \| "dark"/)
  assert.doesNotMatch(text, /import\(['"]\.\/hostTypes\.js/)
})

test('generated html.d.ts exports renderHtml with the four themes', () => {
  const text = readFileSync('tools/api/html.d.ts', 'utf8')
  assert.match(text, /^\/\/ Generated by tools\/gen\/api-dts\.mjs/m)
  assert.match(text, /export function renderHtml\b/)
  assert.match(text, /"document" \| "modern" \| "legal" \| "dark"/)
})

test('MODULES and EMBED list exactly the generated public API declaration files', () => {
  assert.deepEqual(
    MODULES.map((m) => m.out).sort(),
    ['tools/api/html.d.ts', 'tools/api/validate.d.ts'],
  )
  assert.equal(EMBED.out, 'src/embed/antu-embed.d.ts')
})
